/**
 * @file    encoder.h
 * @brief   JGB37-520 四路 AB 相增量式编码器驱动 —— API
 *
 * ======================== 编码器型号 ========================
 *
 *   JGB37-520 减速电机配套 AB 相正交编码器
 *   减速比 1:30，编码器本体 11 PPR（每圈脉冲数）
 *   输出轴每转脉冲数 CPR = 11 × 2(双沿) × 30 = 660
 *
 * ======================== 架构（混合模式）========================
 *
 *   四路编码器使用两种不同的信号采集方案：
 *
 *   C1 → TIMG8 硬件正交编码器模式（QEI）
 *     硬件自动对 AB 相跳变计数，无需 CPU 干预。
 *     SysConfig 中将 TIMG8 设为 Encoder Mode，PB21=A相, PA30=B相。
 *     读取：直接读 TIMG8.CTR 寄存器 → 32 位有符号计数。
 *     精度高、不占 CPU，适合作为速度反馈的主传感器。
 *
 *   C2/C3/C4 → 软件轮询 + SysTick 1kHz 中断
 *     每 1ms 扫描一次 A 相电平跳变（双沿检测：上升沿+下降沿都计数）。
 *     B 相在跳变时刻的电平决定方向。
 *     SysTick 手动初始化（不占外设定时器）。
 *
 *   为什么不是全部用硬件 QEI？
 *     MSPM0G3507 只有 TIMG8 支持 Encoder Mode，无其他正交编码器外设。
 *     1kHz 扫描对 660CPR 的编码器来说已足够（最大 ~90 RPM 不失步）。
 *
 * ======================== 引脚映射 ========================
 *
 *   ┌─────┬──────────┬──────────┬──────────┬──────────┐
 *   │ 编号 │ 对应轮子  │ A 相     │ B 相     │ 采集方式  │
 *   ├─────┼──────────┼──────────┼──────────┼──────────┤
 *   │ C1  │ 右前轮    │ PB21     │ PA30     │ TIMG8 QEI│
 *   │ C2  │ 左前轮    │ PB22     │ PB16     │ 软件扫描  │
 *   │ C3  │ 右后轮    │ PB20     │ PA22     │ 软件扫描* │
 *   │ C4  │ 左后轮    │ PA15     │ PA14     │ 软件扫描  │
 *   └─────┴──────────┴──────────┴──────────┴──────────┘
 *
 *   * C3 AB 相物理接线与其他三路相反 — 软件扫描中已做方向翻转。
 *
 * ======================== 方向约定 ========================
 *
 *   轮子正转（车体前进方向）→ count 正向累加 → rpm 为正
 *   轮子反转（车体倒退方向）→ count 负向累加 → rpm 为负
 *
 * ======================== SysTick 配置 ========================
 *
 *   时钟源 = CPUCLK = 32MHz（SysTick_CTRL_CLKSOURCE = 1）
 *   RELOAD = 31999 → 32000 周期 × 1/32MHz = 1ms → 1kHz 中断
 *
 *   优先级：192（最低）—— 编码器扫描可忍延迟 1~2ms，
 *     但蓝牙 UART 中断(64) 和 MPU6050(0) 不可延迟。
 */

#ifndef ENCODER_H
#define ENCODER_H

#include <stdint.h>
#include <stdbool.h>

/* ===================================================================
 *  编码器编号
 * =================================================================== */

typedef enum {
    ENCODER_C1 = 0,         /**< 右前轮, TIMG8 硬件 QEI（精度最高） */
    ENCODER_C2 = 1,         /**< 左前轮, 软件轮询 */
    ENCODER_C3 = 2,         /**< 右后轮, 软件轮询（AB 相接反，代码已修正） */
    ENCODER_C4 = 3,         /**< 左后轮, 软件轮询 */
    ENCODER_COUNT = 4       /**< 编码器总数 */
} EncoderID_t;

/* ===================================================================
 *  编码器参数
 * =================================================================== */

/** 减速比：电机轴每 30 圈 = 输出轴 1 圈 */
#define ENCODER_GEAR_RATIO      30

/** 编码器线数：每圈 11 个脉冲（单相，仅 A 相上升沿） */
#define ENCODER_PPR             11

/**
 * 电机输出轴每转一圈的编码器脉冲数
 * = PPR × 2(双沿计数) × 减速比
 * = 11 × 2 × 30 = 660
 *
 * 例：若读到 330 个脉冲 → 轮子转了半圈
 */
#define ENCODER_CPR             (ENCODER_PPR * 2 * ENCODER_GEAR_RATIO)

/** 硬件 QEI 的 ×2 模式等效 CPR = 软件双沿一致 */
#define ENCODER_CPR_HW          ENCODER_CPR

/** 软件扫描频率（用于 Encoder_GetSpeed 的 dt 估算） */
#define ENC_SCAN_FREQ_HZ        1000U

/* ===================================================================
 *  API
 * =================================================================== */

void Encoder_Init(void);
void Encoder_Scan(void);
int32_t Encoder_GetCount(EncoderID_t id);
void Encoder_Reset(EncoderID_t id);
void Encoder_ResetAll(void);
bool Encoder_GetSpeed(EncoderID_t id, float dt, float *rpm);
int16_t Encoder_GetDelta(EncoderID_t id);

#endif /* ENCODER_H */
